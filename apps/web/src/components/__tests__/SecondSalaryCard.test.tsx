import '@testing-library/jest-dom';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';
import { makeSecondSalary } from '../../test/fixtures';
import SecondSalaryCard from '../SecondSalaryCard';

const ok = { ok: true as const, value: undefined };
const setup = (secondSalary = makeSecondSalary(), save = vi.fn().mockResolvedValue(ok)) => {
  render(<SecondSalaryCard secondSalary={secondSalary} onSaveTarget={save} />);
  return save;
};

describe('SecondSalaryCard with a target', () => {
  it('explains the idea in one sentence and shows what the portfolio pays', () => {
    setup();
    expect(screen.getByRole('heading', { name: 'Second Salary' })).toBeInTheDocument();
    expect(screen.getByText(/Passive monthly income generated by your invested portfolio/)).toBeInTheDocument();
    expect(screen.getByText('€1,000 / month')).toBeInTheDocument();
    expect(screen.getByText('of €2,500 / month')).toBeInTheDocument();
  });

  it('draws one progress bar, readable without sight', () => {
    setup();
    const bar = screen.getByRole('progressbar', { name: '€1,000 / month of your €2,500 / month target' });
    expect(bar).toHaveAttribute('aria-valuenow', '40');
    expect(screen.getAllByRole('progressbar')).toHaveLength(1);
  });

  it('says which living costs it already covers, without ticks or a fixed range', () => {
    setup();
    expect(screen.getByText('Covers 100% of your rent.')).toBeInTheDocument();
    expect(screen.queryByText(/3,000/)).not.toBeInTheDocument();
    expect(screen.queryByRole('list')).not.toBeInTheDocument();
  });

  it('explains why there is nothing to compare', () => {
    setup(makeSecondSalary({ gap: 'NO_COSTS', milestones: [], reachedMilestone: null }));
    expect(screen.getByText('Add your monthly costs to see what your second salary covers.')).toBeInTheDocument();
  });

  it('changes the target, starting from the current one', async () => {
    const save = setup();
    fireEvent.click(screen.getByRole('button', { name: 'Edit target' }));
    const input = screen.getByLabelText('Monthly target (EUR)');
    expect(input).toHaveValue('2500');

    fireEvent.change(input, { target: { value: '4000' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save target' }));

    await waitFor(() => expect(save).toHaveBeenCalledWith(400_000));
    await waitFor(() => expect(screen.queryByLabelText('Monthly target (EUR)')).not.toBeInTheDocument());
  });
});

describe('SecondSalaryCard without a target', () => {
  const unset = () => makeSecondSalary({ target: null });

  it('explains what a second salary is and asks for a target, with no bar', () => {
    setup(unset());
    expect(screen.getByText(/acting as an independent paycheck that covers your life without working/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Set your target' })).toBeInTheDocument();
    expect(screen.queryByRole('progressbar')).not.toBeInTheDocument();
  });

  it('saves the first target', async () => {
    const save = setup(unset());
    fireEvent.click(screen.getByRole('button', { name: 'Set your target' }));
    fireEvent.change(screen.getByLabelText('Monthly target (EUR)'), { target: { value: '2500' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save target' }));
    await waitFor(() => expect(save).toHaveBeenCalledWith(250_000));
  });

  it('keeps letters out of the amount and says what is wrong without saving', () => {
    const save = setup(unset());
    fireEvent.click(screen.getByRole('button', { name: 'Set your target' }));
    fireEvent.change(screen.getByLabelText('Monthly target (EUR)'), { target: { value: 'abc' } });
    expect(screen.getByLabelText('Monthly target (EUR)')).toHaveValue('');
    fireEvent.click(screen.getByRole('button', { name: 'Save target' }));
    expect(screen.getByText('Enter an amount such as 2500.')).toBeInTheDocument();
    expect(save).not.toHaveBeenCalled();
  });

  it('keeps the form open and shows the problem when saving fails', async () => {
    const save = vi.fn().mockResolvedValue({ ok: false, failure: { kind: 'network', message: 'offline' } });
    setup(unset(), save);
    fireEvent.click(screen.getByRole('button', { name: 'Set your target' }));
    fireEvent.change(screen.getByLabelText('Monthly target (EUR)'), { target: { value: '2500' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save target' }));
    expect(await screen.findByRole('alert')).toBeInTheDocument();
    expect(screen.getByLabelText('Monthly target (EUR)')).toBeInTheDocument();
  });

  it('can be cancelled', () => {
    setup(unset());
    fireEvent.click(screen.getByRole('button', { name: 'Set your target' }));
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));
    expect(screen.getByRole('button', { name: 'Set your target' })).toBeInTheDocument();
  });
});
